"""Build the assumptions register from the configuration, so it cannot drift from the values it describes."""
from __future__ import annotations

import yaml

from ohmetry_dc.models import ProjectConfig


def build_register(cfg: ProjectConfig) -> dict:
    items = []
    for pid, p in cfg.parameters.items():
        if p.status.value == "ASSUMPTION":
            items.append({"id": pid, "name": p.name, "value": p.value, "unit": p.unit, "source": p.source, "revision": p.revision,
                          "confirmation_status": "UNCONFIRMED", "confirmed_by": None, "confirmation_date": None, "notes": p.notes})
    for it in cfg.load_items:
        if it.status.value == "ASSUMPTION":
            items.append({"id": f"load_items.{it.id}", "name": it.description, "value": {"quantity": it.quantity, "unit_rating_kw": it.unit_rating_kw, "power_factor": it.power_factor,
                          "demand_factor": it.demand_factor, "path_a_fraction": it.path_a_fraction}, "unit": "kW, -", "source": it.source, "revision": it.revision,
                          "confirmation_status": "UNCONFIRMED", "confirmed_by": None, "confirmation_date": None, "notes": it.notes})
    return {"schema_version": 1, "note": "Generated by 'build-assumptions-register'. Do not edit by hand: change the configuration and regenerate.", "assumptions": items}


def dump_register(register: dict) -> str:
    return yaml.safe_dump(register, sort_keys=False, allow_unicode=True)
